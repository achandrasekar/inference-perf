class WekaTraceReplayDataGenerator(ReplayGraphSessionGeneratorBase):
    """Data generator that replays LLM requests from Weka trace files."""

    def __init__(
        self,
        api_config: APIConfig,
        config: DataConfig,
        tokenizer: Optional[CustomTokenizer],
        mp_manager: Optional[SyncManager] = None,
        base_seed: Optional[int] = None,
        num_workers: int = 1,
        worker_mode: bool = False,
    ) -> None:
        if not hasattr(config, "weka_trace_replay") or config.weka_trace_replay is None:
            raise ValueError("weka_trace_replay configuration is required for WekaTraceReplayDataGenerator")

        self.weka_config = config.weka_trace_replay

        # Pass the replay config to the parent class
        super().__init__(
            api_config,
            config,
            tokenizer,
            mp_manager=mp_manager,
            base_seed=base_seed,
            num_workers=num_workers,
            replay_config=self.weka_config,
        )

        self.mp_manager = mp_manager
        self.num_workers = max(1, num_workers)
        self.base_seed = base_seed if base_seed is not None else 42

        # Initialize deterministic prompt corpus
        if self.tokenizer is None:
            raise ValueError("Tokenizer is required for WekaTraceReplayDataGenerator")

        if self.config and self.config.corpus_file_path:
            corpus_path = Path(self.config.corpus_file_path)
        else:
            corpus_path = Path(__file__).resolve().parents[1] / "assets" / "shakespeare.txt"

        if not corpus_path.is_file():
            raise FileNotFoundError(f"Prompt corpus file not found: {corpus_path}")

        corpus_text = corpus_path.read_text(encoding="utf-8")
        logger.info(f"Loaded prompt corpus from: {corpus_path} ({len(corpus_text)} chars)")

        base_prompt = "Pick as many lines as you can from these poem lines:\n"
        self._tokenized_corpus = self.tokenizer.get_tokenizer().encode(base_prompt + corpus_text)
        self._corpus_size = len(self._tokenized_corpus)

        self._hash_id_rng = HashIdRandomGenerator(self.base_seed)
        self._cache: Dict[int, List[int]] = {}

        if not worker_mode:
            import pickle

            cache_file = Path("/workspace/weka_sessions_cache.pkl")
            if cache_file.is_file():
                logger.info("Loading pre-built session graphs from cache file...")
                try:
                    with open(cache_file, "rb") as f:
                        sessions = pickle.load(f)
                    logger.info(f"Successfully loaded {len(sessions)} sessions from cache")
                except Exception as e:
                    logger.error(f"Failed to load sessions from cache: {e}. Rebuilding...")
                    traces = self._load_weka_traces()
                    sessions = self._build_sessions_from_traces(traces)
                    # Try to save to cache
                    try:
                        with open(cache_file, "wb") as f:
                            pickle.dump(sessions, f)
                    except Exception as e_save:
                        logger.error(f"Failed to cache built sessions: {e_save}")
            else:
                # Load all WekaTrace records
                traces = self._load_weka_traces()
                sessions = self._build_sessions_from_traces(traces)
                # Try to save to cache
                try:
                    logger.info("Saving built session graphs to cache file...")
                    with open(cache_file, "wb") as f:
                        pickle.dump(sessions, f)
                    logger.info("Successfully cached built sessions")
                except Exception as e:
                    logger.error(f"Failed to cache built sessions: {e}")

            self.initialize_sessions(sessions)

    def _load_weka_traces(self) -> List[WekaTrace]:
        """Loads traces from directories, files, or Hugging Face dataset."""
        raw_traces: List[WekaTrace] = []

        if self.weka_config.trace_directory:
            trace_dir = Path(self.weka_config.trace_directory)
            if not trace_dir.exists() or not trace_dir.is_dir():
                raise ValueError(f"Trace directory does not exist or is not a directory: {trace_dir}")
            files = sorted(trace_dir.glob("*.json"))
            if not files:
                raise ValueError(f"No JSON files found in {trace_dir}")

            for f in files:
                try:
                    blob = json.loads(f.read_text(encoding="utf-8"))
                    raw_traces.append(WekaTrace.model_validate(blob))
                except Exception as e:
                    logger.error(f"Failed to load trace {f.name}: {e}")
                    if not self.weka_config.skip_invalid_files:
                        raise

        elif self.weka_config.trace_files:
            for path in self.weka_config.trace_files:
                f = Path(path)
                if not f.is_file():
                    raise ValueError(f"Trace file does not exist: {path}")
                try:
                    blob = json.loads(f.read_text(encoding="utf-8"))
                    raw_traces.append(WekaTrace.model_validate(blob))
                except Exception as e:
                    logger.error(f"Failed to load trace {f.name}: {e}")
                    if not self.weka_config.skip_invalid_files:
                        raise

        elif self.weka_config.hf_dataset_path:
            repo_id = self.weka_config.hf_dataset_path
            if isinstance(repo_id, dict):
                repo_id = repo_id["path"]
            logger.info(f"Downloading Weka traces from Hugging Face dataset: {repo_id}")
            try:
                # Use raw file download to bypass buggy Feature-type validation in datasets
                local_path = hf_hub_download(repo_id=repo_id, filename="traces.jsonl", repo_type="dataset")
                logger.info(f"Trace file downloaded to {local_path}")

                with open(local_path, "r", encoding="utf-8") as file_stream:
                    for line_idx, line in enumerate(file_stream):
                        if line_idx >= self.weka_config.num_dataset_entries:
                            break
                        if line.strip():
                            try:
                                blob = json.loads(line)
                                raw_traces.append(WekaTrace.model_validate(blob))
                            except Exception as e:
                                logger.error(f"Failed to validate row {line_idx}: {e}")
                                if not self.weka_config.skip_invalid_files:
                                    raise
            except Exception as e:
                raise ValueError(f"Failed to load Hugging Face dataset {repo_id}: {e}") from e

        # Ensure unique trace IDs
        unique_traces: Dict[str, WekaTrace] = {}
        for trace in raw_traces:
            if trace.id in unique_traces:
                raise ValueError(f"Duplicate trace ID found: {trace.id}")
            unique_traces[trace.id] = trace

        return list(unique_traces.values())

    def _build_sessions_from_traces(self, traces: List[WekaTrace]) -> List[ReplaySession]:
        sessions: List[ReplaySession] = []

        if self.num_workers > 1:
            import multiprocessing as mp

            logger.info(f"Building {len(traces)} trace sessions in parallel using {self.num_workers} processes")

            global _global_generator
            _global_generator = self

            tasks = [(trace, idx) for idx, trace in enumerate(traces)]
            ctx = mp.get_context("fork")
            with ctx.Pool(processes=self.num_workers) as pool:
                results = pool.map(_build_session_worker_task_global, tasks)

            for res in results:
                if res is not None:
                    sessions.append(res)
        else:
            logger.info(f"Building {len(traces)} trace sessions sequentially")
            for trace_index, trace in enumerate(traces):
                try:
                    calls_and_warmup = self._reconstruct_raw_calls(trace)
                    if not calls_and_warmup:
                        continue
                    raw_calls, warmup_event = calls_and_warmup

                    graph = build_graph(raw_calls, source_file=f"weka_trace_{trace.id}")
                    if self.weka_config.warmup_cache_priming and warmup_event is not None:
                        self._insert_warmup_event_into_graph(graph, warmup_event)
                        warmup_event = None

                    # Make session ID unique per trace run
                    session_id = f"wekatrace{trace_index}_{trace.id}"
                    sessions.append(
                        ReplaySession(
                            session_id=session_id,
                            source_id=trace.id,
                            session_index=trace_index,
                            graph=graph,
                            warmup_event=warmup_event,
                        )
                    )
                except Exception as e:
                    logger.error(f"Failed to process Weka trace {trace.id}: {e}")
                    if not self.weka_config.skip_invalid_files:
                        raise

        # Shuffle sessions for stress testing
        random.seed(self.base_seed)
        random.shuffle(sessions)
        return sessions

    def _truncate_text_to_len(self, text: str, max_tokens: int) -> str:
        tokens = self.tokenizer.get_tokenizer().encode(text)
        if len(tokens) <= max_tokens:
            return text
        truncated_tokens = tokens[:max_tokens]
        decoded = self.tokenizer.get_tokenizer().decode(truncated_tokens)
        return decoded if isinstance(decoded, str) else " ".join(decoded)

    def _clamp_messages_to_model_limit(self, messages: List[Dict[str, Any]], max_out: int) -> List[Dict[str, str]]:
        if not self.weka_config.max_model_len or self.weka_config.forbid_input_truncation:
            return [{"role": m["role"], "content": m["content"]} for m in messages]
            
        max_in = self.weka_config.max_model_len - max_out - 8192
        if max_in <= 0:
            return [{"role": m["role"], "content": m["content"]} for m in messages]
            
        # 1. Identify system prompt
        sys_msg = None
        start_idx = 0
        sys_len = 0
        if messages and messages[0].get("role") == "system":
            sys_msg = messages[0]
            start_idx = 1
            sys_len = sys_msg.get("token_count") if "token_count" in sys_msg else self.tokenizer.count_tokens(sys_msg["content"])
            
        if sys_len >= max_in:
            # System prompt alone exceeds the budget, truncate it and return
            truncated_content = self._truncate_text_to_len(sys_msg["content"], max_in)
            return [{"role": "system", "content": truncated_content}]
            
        budget = max_in - sys_len
        kept_messages = []
        accumulated_len = 0
        
        # 2. Iterate in reverse over the non-system messages
        for msg in reversed(messages[start_idx:]):
            msg_len = msg.get("token_count") if "token_count" in msg else self.tokenizer.count_tokens(msg["content"])
            if accumulated_len + msg_len <= budget:
                kept_messages.insert(0, msg)
                accumulated_len += msg_len
            else:
                # Fill the remaining budget with a truncated version of the current message
                remaining_budget = budget - accumulated_len
                if remaining_budget > 0:
                    truncated_content = self._truncate_text_to_len(msg["content"], remaining_budget)
                    kept_messages.insert(0, {"role": msg["role"], "content": truncated_content})
                break
                
        # Strip token_count field from dicts to return standard {"role", "content"}
        final_messages = []
        if sys_msg:
            final_messages.append({"role": sys_msg["role"], "content": sys_msg["content"]})
        for m in kept_messages:
            final_messages.append({"role": m["role"], "content": m["content"]})
            
        return final_messages

    def _reconstruct_raw_calls(self, trace: WekaTrace) -> Tuple[List[RawCall], Optional[ReplaySessionEvent]]:
        # Reset local cache for deterministic scope
        self._cache.clear()
        self._hash_id_rng.set_trace_id(trace.id)

        # Build model mappings
        model_map = self._build_model_map(trace)

        # Build Plans
        normals: List[Tuple[int, Union[WekaNormalRequest, WekaStreamingRequest]]] = []
        subagents: List[Tuple[int, WekaSubagentEntry]] = []
        for idx, req in enumerate(trace.requests):
            if isinstance(req, WekaNormalRequest | WekaStreamingRequest):
                normals.append((idx, req))
            elif isinstance(req, WekaSubagentEntry):
                subagents.append((idx, req))

        preamble, detect_normals = _split_off_preamble(normals)
        if preamble:
            normals = sorted(preamble + detect_normals, key=lambda item: (item[1].t if hasattr(item[1], "t") and item[1].t is not None else 0, item[0]))

        trace_bs = self.weka_config.default_block_size
        if hasattr(trace, "block_size") and trace.block_size:
            trace_bs = trace.block_size

        # Resolve warmup start turn
        max_start = len(normals) - 1
        start_k = 0
        if self.weka_config.warmup_snapshot_sampling and max_start > 0:
            rng = random.Random(self.base_seed + abs(hash(trace.id)))
            min_ratio = getattr(self.weka_config, "warmup_snapshot_min_ratio", 0.25)
            max_ratio = getattr(self.weka_config, "warmup_snapshot_max_ratio", 0.75)
            ratio = rng.uniform(min_ratio, max_ratio)
            start_k = int(ratio * len(normals))
            start_k = max(0, min(start_k, max_start))
            logger.info(
                f"Trace {trace.id}: warmup snapshot sampling chose turn {start_k} (ratio {ratio:.3f}, out of {max_start})"
            )
        elif self.weka_config.start_turn_index is not None:
            start_k = min(self.weka_config.start_turn_index, max_start)
            logger.info(f"Trace {trace.id}: start_turn_index config chose turn {start_k} (out of {max_start})")

        first_parent_request_idx = normals[start_k][0] if normals else 0

        parent_plan = _ParentPlan(trace.id, normals, subagents, block_size=trace_bs)

        child_plans: List[_ChildPlan] = []
        for _sa_index, (sa_idx, entry) in enumerate(subagents):
            if sa_idx < first_parent_request_idx:
                logger.debug(
                    f"Trace {trace.id}: pruning subagent {entry.agent_id} spawned at request index {sa_idx} prior to start turn {start_k}"
                )
                continue
            streams = _pack_into_streams(list(entry.requests))
            if not streams:
                streams = [[]]
            multi = len(streams) > 1
            for stream_idx, stream_reqs in enumerate(streams):
                child_sid = f"{trace.id}::sa:{entry.agent_id}"
                if multi:
                    child_sid += f":s{stream_idx}"
                child_plans.append(
                    _ChildPlan(
                        session_id=child_sid,
                        parent_trace_id=trace.id,
                        subagent_index=sa_idx,
                        entry=entry,
                        stream_index=stream_idx,
                        stream_requests=stream_reqs,
                        block_size=trace_bs,
                    )
                )

        # Time warping
        timing = _build_trace_idle_timing(parent_plan, child_plans, self.weka_config.trace_idle_gap_cap_seconds)

        # Call reconstruction helper closures
        def decode_block_tokens(hash_ids: List[int]) -> List[int]:
            tokens: List[int] = []
            for h in hash_ids:
                cached = self._cache.get(h)
                if cached is None:
                    self._hash_id_rng.reseed_for_hash_id(h)
                    start = self._hash_id_rng.randrange(self._corpus_size)
                    end = start + trace_bs
                    cached = self._tokenized_corpus[start:end]
                    if end > self._corpus_size:
                        cached = cached + self._tokenized_corpus[: end - self._corpus_size]
                    self._cache[h] = cached
                tokens.extend(cached)
            return tokens

        def sample_partial_tail_tokens(n: int, seed: str) -> List[int]:
            if n <= 0:
                return []
            digest = hashlib.sha256(seed.encode()).digest()
            offset = int.from_bytes(digest[:8], "big") % max(self._corpus_size - n, 1)
            return list(self._tokenized_corpus[offset : offset + n])

        assert self.tokenizer is not None
        tokenizer_instance = self.tokenizer

        def decode_tokens_to_text(tokens: List[int]) -> str:
            decoded = tokenizer_instance.get_tokenizer().decode(tokens)
            return decoded if isinstance(decoded, str) else " ".join(decoded)

        # Reconstruct Parent Calls
        parent_recon = ConversationReconstructor(
            block_size=trace_bs,
            decode_block_tokens=decode_block_tokens,
            sample_partial_tail_tokens=sample_partial_tail_tokens,
            decode_tokens_to_text=decode_tokens_to_text,
            count_tokens=tokenizer_instance.count_tokens,
        )

        # Warm up the reconstructor state with pruned turns
        for k in range(start_k):
            req = parent_plan.normals[k][1]
            seed = f"{trace.id}:turn_{k}:partial_tail"
            if k == 0:
                parent_recon.init_turn_0(
                    hash_ids=req.hash_ids,
                    in_tokens=req.input_length,
                    tool_tokens=trace.tool_tokens,
                    system_tokens=trace.system_tokens,
                    seed=seed,
                )
            else:
                prev_req = parent_plan.normals[k - 1][1]
                parent_recon.advance_turn(
                    prev_hash_ids=prev_req.hash_ids,
                    prev_in_tokens=prev_req.input_length,
                    prev_out_tokens=prev_req.output_length,
                    curr_hash_ids=req.hash_ids,
                    curr_in_tokens=req.input_length,
                    seed=seed,
                )

        warmup_event = None
        if self.weka_config.warmup_cache_priming and start_k > 0:
            messages_dicts = parent_recon.snapshot_messages()
            messages_dicts = self._clamp_messages_to_model_limit(messages_dicts, max_out=1)
            warmup_event = ReplaySessionEvent(
                call_id=f"sa_warmup_{trace.id}_turn_{start_k - 1}",
                event_id=f"warmup:{trace.id}",
                session_index=-1,
                t_start_ms=0,
                t_end_ms=1000,
                model=model_map.get(parent_plan.normals[start_k - 1][1].model, parent_plan.normals[start_k - 1][1].model),
                messages=messages_dicts,
                expected_output="warmup",
                input_segments=[],
                expected_output_tokens=1,
                temperature=0.0,
                max_tokens_recorded=1,
            )

        parent_calls: List[RawCall] = []
        for k in range(start_k, len(parent_plan.normals)):
            outer_idx, req = parent_plan.normals[k]
            seed = f"{trace.id}:turn_{k}:partial_tail"
            if k == 0:
                parent_recon.init_turn_0(
                    hash_ids=req.hash_ids,
                    in_tokens=req.input_length,
                    tool_tokens=trace.tool_tokens,
                    system_tokens=trace.system_tokens,
                    seed=seed,
                )
            else:
                prev_req = parent_plan.normals[k - 1][1]
                parent_recon.advance_turn(
                    prev_hash_ids=prev_req.hash_ids,
                    prev_in_tokens=prev_req.input_length,
                    prev_out_tokens=prev_req.output_length,
                    curr_hash_ids=req.hash_ids,
                    curr_in_tokens=req.input_length,
                    seed=seed,
                )

            # Retrieve text messages for the prompt
            messages_dicts = parent_recon.snapshot_messages()
            messages_dicts = self._clamp_messages_to_model_limit(messages_dicts, max_out=req.output_length)
            messages = [ReplayMessage(role=m["role"], text=m["content"]) for m in messages_dicts]

            # Reconstruct timing
            t_timing = timing.parent_by_outer_idx[outer_idx]
            t_start_ms = int(t_timing.timestamp_seconds * 1000.0)
            t_end_ms = t_start_ms + int((req.api_time or 0.0) * 1000.0)

            # Completion is generated at next turn or placeholder if last turn
            expected_out_text = ""
            if k + 1 < len(parent_plan.normals):
                # Run lookahead advance to see what assistant message is generated
                lookahead = ConversationReconstructor(
                    block_size=trace_bs,
                    decode_block_tokens=decode_block_tokens,
                    sample_partial_tail_tokens=sample_partial_tail_tokens,
                    decode_tokens_to_text=decode_tokens_to_text,
                    count_tokens=tokenizer_instance.count_tokens,
                )
                lookahead._segments = [
                    RoleSegment(s.role, s.block_start, s.block_count, list(s.tokens), s.content, s.token_count)
                    for s in parent_recon._segments
                ]
                next_req = parent_plan.normals[k + 1][1]
                next_seed = f"{trace.id}:turn_{k + 1}:partial_tail"
                lookahead.advance_turn(
                    prev_hash_ids=req.hash_ids,
                    prev_in_tokens=req.input_length,
                    prev_out_tokens=req.output_length,
                    curr_hash_ids=next_req.hash_ids,
                    curr_in_tokens=next_req.input_length,
                    seed=next_seed,
                )
                # Find the assistant segment added
                for seg in reversed(lookahead._segments):
                    if seg.role == "assistant":
                        expected_out_text = seg.content
                        break
            else:
                # Last turn fallback: sample random tokens from corpus
                out_tokens = sample_partial_tail_tokens(req.output_length, f"{trace.id}:final_parent_turn_completion")
                expected_out_text = decode_tokens_to_text(out_tokens)

            out_msg = ReplayMessage(role="assistant", text=expected_out_text)

            parent_calls.append(
                RawCall(
                    call_id=f"parent_turn_{k}",
                    trace_id=trace.id,
                    t_start_ms=t_start_ms,
                    t_end_ms=t_end_ms,
                    model=model_map.get(req.model, req.model),
                    messages=messages,
                    out_message=out_msg,
                    prompt_tokens=req.input_length,
                    completion_tokens=req.output_length,
                    temperature=0.0,
                    max_tokens_recorded=req.output_length,
                    thread_id=trace.id,
                )
            )

        # Reconstruct Subagent Calls
        child_calls: List[RawCall] = []
        for cp in child_plans:
            child_recon = ConversationReconstructor(
                block_size=trace_bs,
                decode_block_tokens=decode_block_tokens,
                sample_partial_tail_tokens=sample_partial_tail_tokens,
                decode_tokens_to_text=decode_tokens_to_text,
                count_tokens=tokenizer_instance.count_tokens,
            )

            for k, creq in enumerate(cp.stream_requests):
                seed = f"{cp.session_id}:turn_{k}:partial_tail"
                if k == 0:
                    child_recon.init_turn_0(
                        hash_ids=creq.hash_ids,
                        in_tokens=creq.input_length,
                        tool_tokens=cp.entry.tool_tokens,
                        system_tokens=cp.entry.system_tokens,
                        seed=seed,
                    )
                else:
                    prev_creq = cp.stream_requests[k - 1]
                    child_recon.advance_turn(
                        prev_hash_ids=prev_creq.hash_ids,
                        prev_in_tokens=prev_creq.input_length,
                        prev_out_tokens=prev_creq.output_length,
                        curr_hash_ids=creq.hash_ids,
                        curr_in_tokens=creq.input_length,
                        seed=seed,
                    )

                messages_dicts = child_recon.snapshot_messages()
                messages_dicts = self._clamp_messages_to_model_limit(messages_dicts, max_out=creq.output_length)
                messages = [ReplayMessage(role=m["role"], text=m["content"]) for m in messages_dicts]

                t_timing = timing.child_by_session_request[(cp.session_id, k)]
                t_start_ms = int(t_timing.timestamp_seconds * 1000.0)
                t_end_ms = t_start_ms + int((creq.api_time or 0.0) * 1000.0)

                expected_out_text = ""
                if k + 1 < len(cp.stream_requests):
                    lookahead = ConversationReconstructor(
                        block_size=trace_bs,
                        decode_block_tokens=decode_block_tokens,
                        sample_partial_tail_tokens=sample_partial_tail_tokens,
                        decode_tokens_to_text=decode_tokens_to_text,
                        count_tokens=tokenizer_instance.count_tokens,
                    )
                    lookahead._segments = [
                        RoleSegment(s.role, s.block_start, s.block_count, list(s.tokens), s.content, s.token_count)
                        for s in child_recon._segments
                    ]
                    next_creq = cp.stream_requests[k + 1]
                    next_seed = f"{cp.session_id}:turn_{k + 1}:partial_tail"
                    lookahead.advance_turn(
                        prev_hash_ids=creq.hash_ids,
                        prev_in_tokens=creq.input_length,
                        prev_out_tokens=creq.output_length,
                        curr_hash_ids=next_creq.hash_ids,
                        curr_in_tokens=next_creq.input_length,
                        seed=next_seed,
                    )
                    for seg in reversed(lookahead._segments):
                        if seg.role == "assistant":
                            expected_out_text = seg.content
                            break
                else:
                    # Subagent final turn: lookahead to joining parent request
                    subagent_end_t = timing.subagent_end_by_outer_idx.get(cp.subagent_index)
                    joining_parent_req = None
                    joining_parent_idx = None
                    if subagent_end_t is not None:
                        for idx, (p_idx, p_req) in enumerate(parent_plan.normals):
                            p_timing = timing.parent_by_outer_idx.get(p_idx)
                            if p_timing and p_timing.timestamp_seconds >= subagent_end_t:
                                if all(h in p_req.hash_ids for h in creq.hash_ids):
                                    joining_parent_req = p_req
                                    joining_parent_idx = idx
                                    break

                    out_hashes = None
                    if joining_parent_req is not None and joining_parent_idx is not None:
                        parent_prev_req = parent_plan.normals[joining_parent_idx - 1][1] if joining_parent_idx > 0 else None
                        prev_hash_ids = parent_prev_req.hash_ids if parent_prev_req else []
                        curr_hash_ids = joining_parent_req.hash_ids
                        lcp = longest_common_prefix(prev_hash_ids, curr_hash_ids)
                        new_blocks = curr_hash_ids[lcp:]

                        sub_in = creq.hash_ids
                        idx_in_new = -1
                        for i in range(len(new_blocks) - len(sub_in) + 1):
                            if new_blocks[i : i + len(sub_in)] == sub_in:
                                idx_in_new = i
                                break

                        if idx_in_new >= 0:
                            asst_blocks = math.ceil(creq.output_length / trace_bs)
                            out_hashes = new_blocks[idx_in_new + len(sub_in) : idx_in_new + len(sub_in) + asst_blocks]

                    if out_hashes:
                        expected_out_text = decode_tokens_to_text(decode_block_tokens(out_hashes))
                    else:
                        out_tokens = sample_partial_tail_tokens(creq.output_length, f"{cp.session_id}:final_turn_completion")
                        expected_out_text = decode_tokens_to_text(out_tokens)

                out_msg = ReplayMessage(role="assistant", text=expected_out_text)

                child_calls.append(
                    RawCall(
                        # Call ID must match what build_graph uses, ensuring subagent uniqueness
                        call_id=f"sa_{cp.entry.agent_id}_s{cp.stream_index}_turn_{k}",
                        trace_id=trace.id,
                        t_start_ms=t_start_ms,
                        t_end_ms=t_end_ms,
                        model=model_map.get(creq.model, creq.model),
                        messages=messages,
                        out_message=out_msg,
                        prompt_tokens=creq.input_length,
                        completion_tokens=creq.output_length,
                        temperature=0.0,
                        max_tokens_recorded=creq.output_length,
                        thread_id=cp.session_id,
                    )
                )

        # Combine all parent and child calls, then sort chronologically
        all_calls = parent_calls + child_calls
        all_calls.sort(key=lambda c: (c.t_start_ms, c.call_id))
        return all_calls, warmup_event

    def _build_model_map(self, trace: WekaTrace) -> Dict[str, str]:
        """Maps trace-side models to configured api_config or target models."""
        configured = self.weka_config.model_mapping or {}
        if self.weka_config.use_static_model:
            return {m: self.weka_config.static_model_name for m in trace.models}
        return configured

    def _insert_warmup_event_into_graph(self, graph: ReplayGraph, warmup_event: ReplaySessionEvent) -> None:
        """Insert the warmup event directly into the session graph as the sole root node."""
        warmup_id = warmup_event.event_id

        # Calculate total input tokens (estimate from messages)
        total_input_tokens = sum(len(msg.get("content", "")) // 4 for msg in warmup_event.messages)
        total_input_tokens = max(1, total_input_tokens)

        input_segments = [
            InputSegment(
                type="unique",
                message_count=len(warmup_event.messages),
                token_count=total_input_tokens,
            )
        ]

        graph_call = GraphCall(
            call_id=warmup_event.call_id,
            model=warmup_event.model if hasattr(warmup_event, "model") else "",
            messages=warmup_event.messages,
            input_segments=input_segments,
            expected_output="warmup",
            expected_output_tokens=1,
            total_input_tokens=total_input_tokens,
            temperature=0.0,
            max_tokens_recorded=1,
        )

        graph_event = GraphEvent(
            event_id=warmup_id,
            call=graph_call,
            predecessor_event_ids=[],
            predecessor_dependency_types={},
            wait_ms=0,
            t_start_ms=0,
            t_end_ms=0,
        )

        # Add warmup event to graph.events
        graph.events[warmup_id] = graph_event

        # Update existing root events to depend on the warmup event
        for root_id in graph.root_event_ids:
            if root_id in graph.events:
                # Add warmup_id to predecessors of the root event
                graph.events[root_id].predecessor_event_ids.append(warmup_id)

        # Set graph.root_event_ids to contain ONLY the warmup event
        graph.root_event_ids = [warmup_id]
