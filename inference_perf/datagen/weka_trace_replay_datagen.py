@dataclass
class RoleSegment:
    role: Literal["system", "user", "assistant"]
    block_start: int
    block_count: int
    tokens: List[int]
    content: str
    token_count: int


def longest_common_prefix(prev_hash_ids: List[int], curr_hash_ids: List[int]) -> int:
    n = min(len(prev_hash_ids), len(curr_hash_ids))
    for i in range(n):
        if prev_hash_ids[i] != curr_hash_ids[i]:
            return i
    return n


def truncate_synth_buf_at_block(
    segments: List[RoleSegment],
    target_blocks: int,
    block_size: int,
    decode_tokens_to_text: Any,
    count_tokens: Any,
    prev_partial_tail: int = 0,
) -> Optional[int]:
    if target_blocks <= 0:
        had_segments = len(segments) > 0
        segments.clear()
        return 0 if had_segments else None

    cursor = 0
    for i, seg in enumerate(segments):
        if cursor + seg.block_count < target_blocks:
            cursor += seg.block_count
            continue
        if cursor + seg.block_count == target_blocks:
            disturbed: Optional[int] = None
            if prev_partial_tail > 0 and len(seg.tokens) > 0:
                stripped_n = min(prev_partial_tail, len(seg.tokens))
                seg.tokens = seg.tokens[:-stripped_n]
                seg.content = decode_tokens_to_text(seg.tokens)
                seg.token_count = count_tokens(seg.content)
                disturbed = i
            deleted_past_boundary = i + 1 < len(segments)
            del segments[i + 1 :]
            if disturbed is None and deleted_past_boundary:
                disturbed = i + 1
            return disturbed
        if cursor == target_blocks:
            del segments[i:]
            return i
        kept_blocks = target_blocks - cursor
        kept_tokens_n = min(len(seg.tokens), kept_blocks * block_size)
        seg.block_count = kept_blocks
        seg.tokens = seg.tokens[:kept_tokens_n]
        seg.content = decode_tokens_to_text(seg.tokens)
        seg.token_count = count_tokens(seg.content)
        del segments[i + 1 :]
        return i
    return None


class ConversationReconstructor:
    """Reconstructs turn-by-turn prompts and completions deterministically."""

    def __init__(
        self,
        block_size: int,
        decode_block_tokens: Any,
        sample_partial_tail_tokens: Any,
        decode_tokens_to_text: Any,
        count_tokens: Any,
    ):
        self.block_size = block_size
        self.decode_block_tokens = decode_block_tokens
        self.sample_partial_tail_tokens = sample_partial_tail_tokens
        self.decode_tokens_to_text = decode_tokens_to_text
        self.count_tokens = count_tokens
        self._segments: List[RoleSegment] = []
        self._last_disturbance_at: Optional[int] = None

    def init_turn_0(
        self,
        hash_ids: List[int],
        in_tokens: int,
        tool_tokens: int,
        system_tokens: int,
        seed: str,
    ) -> None:
        bs = self.block_size
        m_full = in_tokens // bs
        partial_tail_tokens_n = in_tokens - m_full * bs
        covered_blocks = min(m_full, len(hash_ids))
        missing_block_tokens = (m_full - covered_blocks) * bs

        cursor = 0
        segs: List[RoleSegment] = []

        if tool_tokens > 0 or system_tokens > 0:
            prefix_tokens = tool_tokens + system_tokens
            prefix_blocks = math.ceil(prefix_tokens / bs)
            if prefix_blocks > 0:
                if prefix_blocks > len(hash_ids):
                    # Fallback or clamp if missing prefix hash blocks
                    prefix_blocks = len(hash_ids)
                if prefix_blocks > 0:
                    seg_tokens = self.decode_block_tokens(hash_ids[cursor : cursor + prefix_blocks])
                    content = self.decode_tokens_to_text(seg_tokens)
                    segs.append(
                        RoleSegment(
                            role="system",
                            block_start=cursor,
                            block_count=prefix_blocks,
                            tokens=seg_tokens,
                            content=content,
                            token_count=self.count_tokens(content),
                        )
                    )
                    cursor += prefix_blocks

        user_blocks = covered_blocks - cursor
        user_tokens = self.decode_block_tokens(hash_ids[cursor : cursor + user_blocks])
        synth_tail_n = missing_block_tokens + partial_tail_tokens_n
        if synth_tail_n > 0:
            user_tokens.extend(self.sample_partial_tail_tokens(synth_tail_n, seed))
        content = self.decode_tokens_to_text(user_tokens)
        segs.append(
            RoleSegment(
                role="user",
                block_start=cursor,
                block_count=user_blocks,
                tokens=user_tokens,
                content=content,
                token_count=self.count_tokens(content),
            )
        )

        self._segments = segs
        self._last_disturbance_at = None

    def advance_turn(
        self,
        prev_hash_ids: List[int],
        prev_in_tokens: int,
        prev_out_tokens: int,
        curr_hash_ids: List[int],
        curr_in_tokens: int,
        seed: str,
    ) -> None:
        bs = self.block_size
        m_curr = len(curr_hash_ids)
        m_curr_full = curr_in_tokens // bs
        missing_block_tokens = max(0, (m_curr_full - m_curr) * bs)
        lcp = longest_common_prefix(prev_hash_ids, curr_hash_ids)
        prev_partial_tail = prev_in_tokens % bs

        truncate_disturbance = truncate_synth_buf_at_block(
            self._segments,
            lcp,
            bs,
            decode_tokens_to_text=self.decode_tokens_to_text,
            count_tokens=self.count_tokens,
            prev_partial_tail=prev_partial_tail,
        )
        self._last_disturbance_at = truncate_disturbance

        new_blocks = curr_hash_ids[lcp:m_curr]
        new_partial_tail_n = curr_in_tokens % bs
        new_region_tokens = self.decode_block_tokens(new_blocks)
        synth_tail_n = missing_block_tokens + new_partial_tail_n
        if synth_tail_n > 0:
            new_region_tokens.extend(self.sample_partial_tail_tokens(synth_tail_n, seed))
        new_blocks_count = m_curr - lcp

        asst_blocks_target = math.ceil(prev_out_tokens / bs) if prev_out_tokens > 0 else 0
        if not any(seg.role == "user" for seg in self._segments):
            asst_blocks_target = 0
        asst_blocks = min(asst_blocks_target, new_blocks_count)
        asst_emit_size = asst_blocks * bs

        cursor = lcp
        if asst_blocks > 0:
            asst_tokens = new_region_tokens[:asst_emit_size]
            content = self.decode_tokens_to_text(asst_tokens)
            self._segments.append(
                RoleSegment(
                    role="assistant",
                    block_start=cursor,
                    block_count=asst_blocks,
                    tokens=asst_tokens,
                    content=content,
                    token_count=self.count_tokens(content),
                )
            )
            cursor += asst_blocks

        user_blocks = new_blocks_count - asst_blocks
        user_tokens = new_region_tokens[asst_emit_size:]
        if len(user_tokens) > 0:
            content = self.decode_tokens_to_text(user_tokens)
            self._segments.append(
                RoleSegment(
                    role="user",
                    block_start=cursor,
                    block_count=user_blocks,
                    tokens=user_tokens,
                    content=content,
                    token_count=self.count_tokens(content),
                )
            )

    def snapshot_messages(self) -> List[Dict[str, Any]]:
        return [{"role": s.role, "content": s.content, "token_count": s.token_count} for s in self._segments]


